// 发起函数：和练习 2 一样（每块 256 个线程；列块数盖住 M，行块数盖住 N），已写好。
static void my_v4a(const float* X, const float* W, float* Y, int N, int K, int M) {
    const int threads = 256;
    const int blocks_x = (M + threads - 1) / threads;   // Y 的列方向要几块
    const int blocks_y = (N + TOK - 1) / TOK;           // Y 的行方向要几块
